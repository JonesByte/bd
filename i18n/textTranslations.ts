export function translateText(lang: Language, text: string, values: Record<string, string | number> = {}): string {
  const key = text.replace(/\s+/g, ' ').trim();
  const translated = lang === 'pt-BR' ? key : TEXT_TRANSLATIONS[key]?.[lang] ?? key;
  const leading = text.match(/^\s*/)?.[0] ?? '';
  const trailing = text.match(/\s*$/)?.[0] ?? '';
  return leading + translated.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match)) + trailing;
}
